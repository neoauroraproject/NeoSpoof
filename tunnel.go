// tunnelMeta is the summary the panel shows alongside the generated config pair.
type tunnelMeta struct {
	Primary   string   `json:"primary"`
	Pool      []string `json:"pool"`
	PeerReal  string   `json:"peer_real_ip"`
	LocalReal string   `json:"real_ip"`
	DataPort  int      `json:"data_port"`
	ICMPID    int      `json:"icmp_id"`
	PSK       string   `json:"pre_shared_key"`
}

const clientTmpl = `# NeoSpoof client config — generated by spoofd.
# spoofed_ip_pool holds only sources confirmed to survive the path to the server.
real_ip         = "{{client_real}}"
peer_real_ip    = "{{server_real}}"
spoofed_ip      = "{{primary}}"
spoofed_ip_pool = {{pool}}
peer_spoofed_ip = "{{primary}}"
data_port       = {{port}}
icmp_id         = {{id}}
pre_shared_key  = "{{psk}}"
allowed_peers   = {{pool}}
tunnel_count    = {{tcount}}
mtu             = {{mtu}}
initial_cwnd    = {{cwnd}}
interface       = "{{iface}}"
socks5_port     = {{socks}}
`

const serverTmpl = `# NeoSpoof server config — generated by spoofd on the receiving server.
# NOTE: spoofed_ip/spoofed_ip_pool below are this server's OWN reply sources.
# Validate them by running the spoof test in the reverse direction too.
real_ip         = "{{server_real}}"
peer_real_ip    = "{{client_real}}"
spoofed_ip      = "{{primary}}"
spoofed_ip_pool = {{pool}}
peer_spoofed_ip = "{{primary}}"
data_port       = {{port}}
icmp_id         = {{id}}
pre_shared_key  = "{{psk}}"
allowed_peers   = {{pool}}
tunnel_count    = {{tcount}}
mtu             = {{mtu}}
initial_cwnd    = {{cwnd}}
interface       = "{{iface}}"
socks5_port     = {{socks}}
`

// buildTunnelConfig turns the spoofed IPs that passed into a matched client and
// server config pair. peerReal is the sender's real IP (the tunnel client), and
// localReal is this machine's real IP (the tunnel server).
func buildTunnelConfig(passing []string, peerReal, localReal string, set settings) (clientTOML, serverTOML string, meta tunnelMeta, err error) {
	if len(passing) == 0 {
		return "", "", tunnelMeta{}, errInput("هیچ آی‌پی سالمی برای ساخت تانل نیست")
	}
	if peerReal == "" {
		peerReal = "0.0.0.0"
	}
	if localReal == "" {
		localReal = "0.0.0.0"
	}
	psk, err := randHex(32)
	if err != nil {
		return "", "", tunnelMeta{}, err
	}
	port, err := randRange(20000, 60000)
	if err != nil {
		return "", "", tunnelMeta{}, err
	}
	id, err := randRange(1, 0xffff)
	if err != nil {
		return "", "", tunnelMeta{}, err
	}
	primary := passing[0]
	pool := poolTOML(passing)
	kv := map[string]string{
		"client_real": peerReal,
		"server_real": localReal,
		"primary":     primary,
		"pool":        pool,
		"port":        strconv.Itoa(port),
		"id":          strconv.Itoa(id),
		"psk":         psk,
		"socks":       "1080",
		"iface":       ifaceToward(peerReal),
		"tcount":      strconv.Itoa(set.TunnelCount),
		"mtu":         strconv.Itoa(set.MTU),
		"cwnd":        strconv.FormatFloat(set.InitialCwnd, 'f', 1, 64),
	}
	meta = tunnelMeta{Primary: primary, Pool: passing, PeerReal: peerReal, LocalReal: localReal, DataPort: port, ICMPID: id, PSK: psk}
	return fillTemplate(clientTmpl, kv), fillTemplate(serverTmpl, kv), meta, nil
}

// neoPair is a matched NeoSpoof config pair for one tunnel/location: the
// panel runs ClientTOML locally (exposing SocksPort), and the exit server runs
// ServerTOML. Both halves share psk/data_port/icmp_id, so the pair works
// together with no further editing.
type neoPair struct {
	ClientTOML string
	ServerTOML string
	PeerReal   string // exit server's real IP
	LocalReal  string // this machine's real IP
	Primary    string
	Pool       []string
	DataPort   int
	ICMPID     int
	PSK        string
	SocksPort  int
}

// renderNeoPair builds a matched client/server pair for one tunnel/location:
// this machine is the client, serverRealIP is the exit server that runs the
// server side, pool is the spoofed source IPs (the ones that passed the test),
// and socksPort is this tunnel's own local SOCKS5 port.
func renderNeoPair(serverRealIP string, pool []string, socksPort int, set settings) (neoPair, error) {
	if len(pool) == 0 {
		return neoPair{}, errInput("لیست آی‌پی اسپوف خالی است")
	}
	if serverRealIP == "" {
		serverRealIP = "0.0.0.0"
	}
	clientReal := "0.0.0.0"
	if ip := net.ParseIP(serverRealIP).To4(); ip != nil {
		if out, err := outboundIP(ip); err == nil {
			clientReal = out.String()
		}
	}
	psk, err := randHex(32)
	if err != nil {
		return neoPair{}, err
	}
	port, err := randRange(20000, 60000)
	if err != nil {
		return neoPair{}, err
	}
	id, err := randRange(1, 0xffff)
	if err != nil {
		return neoPair{}, err
	}
	kv := map[string]string{
		"client_real": clientReal,
		"server_real": serverRealIP,
		"primary":     pool[0],
		"pool":        poolTOML(pool),
		"port":        strconv.Itoa(port),
		"id":          strconv.Itoa(id),
		"psk":         psk,
		"socks":       strconv.Itoa(socksPort),
		"iface":       ifaceToward(serverRealIP),
		"tcount":      strconv.Itoa(set.TunnelCount),
		"mtu":         strconv.Itoa(set.MTU),
		"cwnd":        strconv.FormatFloat(set.InitialCwnd, 'f', 1, 64),
	}
	return neoPair{
		ClientTOML: fillTemplate(clientTmpl, kv),
		ServerTOML: fillTemplate(serverTmpl, kv),
		PeerReal:   serverRealIP,
		LocalReal:  clientReal,
		Primary:    pool[0],
		Pool:       pool,
		DataPort:   port,
		ICMPID:     id,
		PSK:        psk,
		SocksPort:  socksPort,
	}, nil
}

// serverSetupCommand is the single copy-paste block the operator runs on the
// exit server: it saves the matching server config, then launches the
// NeoSpoof server core. The server binary must already be built and present
// (cargo build --release) next to where the command runs.
func serverSetupCommand(serverTOML string) string {
	var b strings.Builder
	b.WriteString("# روی سرور خارج اجرا کنید (باینری server باید کنار دستور باشد).\n")
	b.WriteString("mkdir -p ~/neospoof && cat > ~/neospoof/server.toml <<'NEOSPOOFEOF'\n")
	b.WriteString(serverTOML)
	if !strings.HasSuffix(serverTOML, "\n") {
		b.WriteString("\n")
	}
	b.WriteString("NEOSPOOFEOF\n")
	b.WriteString("sudo ./server --config ~/neospoof/server.toml")
	return b.String()
}

// extractServerTOML pulls the server config body out of a pasted blob: if it
// carries the installer heredoc markers (NEOSPOOFEOF), return what is between them;
// otherwise return the text as-is (assumed to be a raw server.toml). The legacy
// CANDYEOF marker is still accepted so blobs saved before the rename keep working.
func extractServerTOML(s string) string {
	marker := "NEOSPOOFEOF"
	i := strings.Index(s, marker)
	if i < 0 {
		if j := strings.Index(s, "CANDYEOF"); j >= 0 {
			marker, i = "CANDYEOF", j
		}
	}
	if i < 0 {
		return strings.TrimSpace(s)
	}
	rest := s[i+len(marker):]
	// Skip the rest of the opener line (e.g. the closing quote of <<'NEOSPOOFEOF'),
	// so the body starts at the first config line, not a stray quote.
	if nl := strings.IndexByte(rest, '\n'); nl >= 0 {
		rest = rest[nl+1:]
	}
	if j := strings.Index(rest, marker); j >= 0 {
		return strings.TrimSpace(rest[:j])
	}
	return strings.TrimSpace(rest)
}

// tomlValue reads the quoted string value of `key = "..."` from a TOML body.
// It matches the key only as a whole word at the start of a (trimmed) line, so
// peer_real_ip and real_ip do not collide.
func tomlValue(body, key string) string {
	for _, line := range strings.Split(body, "\n") {
		t := strings.TrimSpace(line)
		if !strings.HasPrefix(t, key) {
			continue
		}
		rest := strings.TrimSpace(t[len(key):])
		if strings.HasPrefix(rest, "=") {
			return strings.Trim(strings.TrimSpace(rest[1:]), `"`)
		}
	}
	return ""
}

// setTOMLString rewrites the value of `key = "..."`, preserving the line indent.
func setTOMLString(body, key, val string) string {
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, key) && strings.Contains(t[len(key):], "=") {
			indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
			lines[i] = indent + key + "         = \"" + val + "\""
		}
	}
	return strings.Join(lines, "\n")
}

// setTOMLNumber rewrites the value of a bare numeric `key = N` line (mtu,
// tunnel_count, initial_cwnd …), preserving the line indent. Unlike
// setTOMLString it writes the value unquoted, as TOML numbers require.
func setTOMLNumber(body, key, val string) string {
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, key) && strings.Contains(t[len(key):], "=") {
			indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
			lines[i] = indent + key + " = " + val
		}
	}
	return strings.Join(lines, "\n")
}

// poolCount returns how many spoofed IPs a config's spoofed_ip_pool line holds.
func poolCount(toml string) int {
	for _, line := range strings.Split(toml, "\n") {
		t := strings.TrimSpace(line)
		if !strings.HasPrefix(t, "spoofed_ip_pool") {
			continue
		}
		i := strings.IndexByte(t, '[')
		j := strings.LastIndexByte(t, ']')
		if i < 0 || j <= i {
			return 0
		}
		if inner := strings.TrimSpace(t[i+1 : j]); inner != "" {
			return strings.Count(inner, ",") + 1
		}
		return 0
	}
	return 0
}

// ifaceToward returns the local NIC name used to reach ipStr, or "eth0" when it
// can't be determined (unspecified or unparseable address).
func ifaceToward(ipStr string) string {
	ip := net.ParseIP(ipStr).To4()
	if ip == nil || ip.IsUnspecified() {
		return "eth0"
	}
	return outboundInterface(ip)
}

// outboundInterface finds the network interface that owns the local source
// address used to reach dst, so generated configs bind to the real NIC instead
// of a hardcoded "eth0". Falls back to "eth0".
func outboundInterface(dst net.IP) string {
	local, err := outboundIP(dst)
	if err != nil || local == nil {
		return "eth0"
	}
	ifaces, err := net.Interfaces()
	if err != nil {
		return "eth0"
	}
	for _, iface := range ifaces {
		if iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		addrs, err := iface.Addrs()
		if err != nil {
			continue
		}
		for _, a := range addrs {
			if ipnet, ok := a.(*net.IPNet); ok && ipnet.IP.To4() != nil && ipnet.IP.Equal(local) {
				return iface.Name
			}
		}
	}
	return "eth0"
}

func fillTemplate(tmpl string, kv map[string]string) string {
	for k, v := range kv {
		tmpl = strings.ReplaceAll(tmpl, "{{"+k+"}}", v)
	}
	return tmpl
}

func poolTOML(ips []string) string {
	q := make([]string, len(ips))
	for i, ip := range ips {
		q[i] = `"` + ip + `"`
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func randHex(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// randRange returns a crypto-random int in [min, max).
func randRange(min, max int) (int, error) {
	if max <= min {
		return min, nil
	}
	var b [4]byte
	if _, err := rand.Read(b[:]); err != nil {
		return 0, err
	}
	return min + int(binary.BigEndian.Uint32(b[:])%uint32(max-min)), nil
}
